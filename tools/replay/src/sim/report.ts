import type { ScenarioResult } from './scenarios';

/** Section 2A switch rule thresholds (non-battery part; battery + fps come from the on-device benchmark). */
export const SWITCH_RULE = {
  maxP95StalenessS: 60,
  minDeliveryRate: 0.98,
  deliveryWindowS: 30,
  maxExtraBatteryPct: 25,
};

const f = (x: number, d = 1) => (Number.isFinite(x) ? x.toFixed(d) : '—');
const pc = (x: number) => `${(x * 100).toFixed(1)}%`;

export interface FunctionVerdict {
  fn: string;
  p2pPasses: boolean;
  reason: string;
}

export function verdicts(results: ScenarioResult[]): FunctionVerdict[] {
  const p2p = results.filter((r) => r.mode === 'p2p');
  const drive = p2p.find((r) => r.name === 'drive-1h');
  const out: FunctionVerdict[] = [];
  if (drive?.staleness) {
    const ok = drive.staleness.p95S <= SWITCH_RULE.maxP95StalenessS;
    out.push({ fn: 'presence', p2pPasses: ok, reason: `p95 staleness ${f(drive.staleness.p95S)} s (limit ${SWITCH_RULE.maxP95StalenessS} s)` });
  }
  for (const key of ['emotes', 'arrivals'] as const) {
    const worst = Math.min(...p2p.map((r) => r[key].rate));
    out.push({
      fn: key,
      p2pPasses: worst >= SWITCH_RULE.minDeliveryRate,
      reason: `worst delivery ${pc(worst)} within ${SWITCH_RULE.deliveryWindowS} s (limit ${pc(SWITCH_RULE.minDeliveryRate)})`,
    });
  }
  return out;
}

export function renderBenchmarkMarkdown(results: ScenarioResult[]): string {
  const rows = results
    .map(
      (r) =>
        `| ${r.name} | ${r.mode} | ${r.phones} | ${r.staleness ? `${f(r.staleness.p50S)} / ${f(r.staleness.p95S)}` : '—'} | ${pc(r.emotes.rate)} (${r.emotes.deliveredWithin30s}/${r.emotes.sent}), p95 ${f(r.emotes.p95S)} s | ${pc(r.arrivals.rate)} (${r.arrivals.deliveredWithin30s}/${r.arrivals.sent}), p95 ${f(r.arrivals.p95S)} s | ${r.relayEventsPublished} | ${pc(r.directShare)} | ${r.wakePings} |`,
    )
    .join('\n');
  const v = verdicts(results)
    .map((x) => `| ${x.fn} | ${x.p2pPasses ? 'P2P' : '**central PC**'} | ${x.reason} |`)
    .join('\n');
  return `<!-- generated by \`pnpm sim -- docs/P2P-BENCHMARK.sim.md\`; do not edit by hand -->
### Simulator results

| Scenario | Mode | Phones | Driver staleness p50 / p95 (s) | Emotes → dozing phone | Arrivals → dozing phone | Relay events | Direct share | Wake pings |
|---|---|---|---|---|---|---|---|---|
${rows}

### Switch-rule verdict (network part)

| Function | Transport | Why |
|---|---|---|
${v}
`;
}
