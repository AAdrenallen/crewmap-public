// Regenerates apps/mobile/src/ui/shell/licenses.generated.ts from ASSETS_LICENSES.md (rendered in Settings → Help).
import fs from 'node:fs';
const md = fs.readFileSync(new URL('../ASSETS_LICENSES.md', import.meta.url), 'utf8');
const clean = (s) => s.replace(/`/g, '').replace(/\s+/g, ' ').trim();
const rows = [];
const notes = [];
for (const line of md.split(/\r?\n/)) {
  if (line.startsWith('|')) {
    const c = line.split('|').slice(1, -1).map(clean);
    if (c.length === 3 && c[0] !== 'Asset' && !/^-+$/.test(c[0])) rows.push({ asset: c[0], source: c[1], licence: c[2] });
  } else if (line.trim() && !line.startsWith('#')) notes.push(clean(line));
}
const out = `// Generated by tools/gen-licenses.mjs from ASSETS_LICENSES.md. Do not edit.\nexport const LICENSE_ROWS: { asset: string; source: string; licence: string }[] = ${JSON.stringify(rows, null, 2)};\nexport const LICENSE_NOTES: string[] = ${JSON.stringify(notes, null, 2)};\n`;
fs.writeFileSync(new URL('../apps/mobile/src/ui/shell/licenses.generated.ts', import.meta.url), out);
console.log(rows.length, 'rows');
